def cross_version(workers=CROSS_WORKERS, repo=REPO, py312=PY312, progress=False):
    """Regenerate every stdlib artifact under 3.11 and 3.12 and compare the canonical digests.

    The worker count is not recorded: every producer merges its units in task order before any
    aggregation, so the bytes are worker-independent and a re-run reproduces this file exactly.
    """
    require(Path(py312).exists(), 'the 3.12 interpreter is required: ' + str(py312))
    interpreters = {'py311': (sys.executable, {}), 'py312': (str(py312), {'PYTHONPATH': '.'})}
    rows, versions = [], {}
    for label, (binary, extra) in sorted(interpreters.items()):
        versions[label] = _run(binary, '-c', 'import sys;print(sys.version.split()[0])').stdout.strip()
    with tempfile.TemporaryDirectory(prefix='vericost565_cross_') as base:
        for label, (binary, extra) in sorted(interpreters.items()):
            folder = Path(base) / label
            folder.mkdir()
            environment = dict(os.environ, **extra)
            for path, argv, name, volatile, committed in _artifacts():
                command = tuple(item.format(out=folder, workers=workers) for item in argv)
                clock = time.perf_counter()
                done = _run(binary, '-m', *command, cwd=str(repo), env=environment)
                if done.returncode != 0:
                    raise RuntimeError('%s could not regenerate %s: %s'
                                       % (label, path, done.stderr.strip().splitlines()[-1:]))
                if progress:
                    print(compact({'regenerated': path, 'interpreter': label,
                                   'seconds': round(time.perf_counter() - clock, 1)}), flush=True)
        for path, argv, name, volatile, committed in _artifacts():
            produced = {label: _canonical(Path(base) / label / name, volatile)
                        for label in interpreters}
            row = {'path': path, 'sha256_py311': produced['py311'],
                   'sha256_py312': produced['py312'],
                   'identical': produced['py311'] == produced['py312'],
                   'volatile_keys': list(volatile)}
            if committed is not None and Path(committed).exists():
                row['committed_sha256'] = _canonical(committed, volatile)
                row['matches_committed'] = row['committed_sha256'] == produced['py311']
            else:
                row['committed_sha256'] = None
                row['matches_committed'] = None
            rows.append(row)
    broken = [row['path'] for row in rows if not row['identical']]
    if broken:
        raise RuntimeError('cross-version bytes differ: ' + ','.join(broken))
    return {'schema': CROSS_SCHEMA, 'version': VERSION,
            'interpreters': {label: versions[label] for label in sorted(versions)},
            'artifacts': rows,
            'excluded': [{'path': 'faultda_bench/reports/vericost565/learned_policies.json',
                          'reason': 'LinUCB training requires numpy; numpy is not installed for '
                                    'the local 3.12.13 interpreter and cannot be installed '
                                    'offline',
                          'mitigation': 'every consumer of the artifact (learned_eval.json, '
                                        'offline_eval.json, analysis.json) is regenerated under '
                                        'both interpreters from the committed artifact'}],
            'api_calls': 0, 'cny_spent': '0.000000'}


# ---- the audit ----------------------------------------------------------------------------------
def audit(parts=('v46', 'allowlist', 'write_once', 'no_network', 'replay', 'secret_scan'),
          workers=1):
    out = {'schema': SCHEMA, 'version': VERSION, 'parts': list(parts)}
    if 'v46' in parts:
        out['v46_unchanged'] = v46_unchanged()
    if 'allowlist' in parts:
        out['diff_allowlist'] = diff_allowlist()
    if 'write_once' in parts:
        out['write_once'] = write_once()
    if 'no_network' in parts:
        out['no_network'] = no_network()
    if 'replay' in parts:
        out['replay_outputs'] = replay_outputs(workers)
    if 'secret_scan' in parts:
        out['secret_scan'] = secret_scan()
        if not out['secret_scan']['clean']:
            raise RuntimeError('secret scan found a match')
    out['api_calls'] = 0
    out['cny_spent'] = '0.000000'
    return out


