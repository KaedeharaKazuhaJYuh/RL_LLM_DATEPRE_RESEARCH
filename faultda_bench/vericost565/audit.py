    args = parser.parse_args()
    clock = time.perf_counter()
    if args.cross_version:
        produced = cross_version(args.workers, progress=True)
        target = Path(args.output or CROSS)
        if target.exists():
            # Write-once: a later run re-verifies the recorded proof instead of overwriting it.
            recorded = json.loads(target.read_text(encoding='utf-8')) == canon(produced)
            if not recorded:
                print('cross-version proof differs from the recorded file', file=sys.stderr)
                raise SystemExit(1)
        else:
            write_json_once(target, produced)
        print(compact({'cross_version': str(target), 'sha256': sha_json(produced),
                       'recorded': target.exists(),
                       'identical': all(row['identical'] for row in produced['artifacts']),
                       'artifacts': [{'path': row['path'], 'identical': row['identical'],
                                      'matches_committed': row['matches_committed']}
                                     for row in produced['artifacts']],
                       'excluded': [row['path'] for row in produced['excluded']],
                       'seconds_wall': round(time.perf_counter() - clock, 1)}))
        raise SystemExit(0)
    chosen = []
    if args.all:
        chosen = ['v46', 'allowlist', 'write_once', 'no_network', 'replay', 'secret_scan']
    else:
        chosen = ([name for name, flag in (('write_once', args.write_once),
                                           ('no_network', args.no_network),
                                           ('replay', args.replay),
                                           ('secret_scan', args.secret_scan)) if flag]
                  or ['v46', 'allowlist', 'write_once'])
    try:
        report = audit(tuple(chosen), args.workers)
    except RuntimeError as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(1)
    if args.output:
        write_json_once(args.output, report)
    print(compact(dict(report, seconds_wall=round(time.perf_counter() - clock, 1))))
