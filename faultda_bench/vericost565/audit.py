def _run(*args, **extra):
    return subprocess.run(args, capture_output=True, text=True, **extra)


# ---- frozen evidence ----------------------------------------------------------------------------
def v46_unchanged():
    """Re-hash every entry of the 660-file freeze through the pinned-path resolver."""
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    for name, digest in catalog['files'].items():
        if sha(pinned_path(ROOT.parent, name)) != digest:
            raise RuntimeError('frozen bytes changed: ' + name)
    return {'files_verified': len(catalog['files']), 'catalog_sha256': sha(CATALOG)}


def diff_allowlist(repo=REPO, base=BASE):
    """Only the seven allowlisted paths may be modified, deleted or renamed since the base."""
    changed = suite.lines(repo, 'diff', '--name-only', '--diff-filter=MDR', base + '..HEAD')
    extra = [name for name in changed if name not in ALLOWLIST]
    if extra:
        raise RuntimeError('path outside the edit allowlist: ' + ','.join(extra))
    return {'base': base, 'changed': changed, 'allowlist': len(ALLOWLIST)}


def write_once(repo=REPO):
    """The same git checks the suite preconditions use, over every write-once path."""
    states = suite.write_once(repo=repo, label='write_once')
    return {'paths': len(states),
            'status': {path: state['status'] for path, state in sorted(states.items())}}


# ---- the no-network / no-provider guard ---------------------------------------------------------
def _scan_source(path):
    """AST and literal scan of one module; returns the list of findings, empty when clean."""
    text = Path(path).read_text(encoding='utf-8')
    found = []
    for node in ast.walk(ast.parse(text, filename=str(path))):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split('.')[0] in BLOCKED_MODULES:
                    found.append('import ' + alias.name)
        elif isinstance(node, ast.ImportFrom):
            if (node.module or '').split('.')[0] in BLOCKED_MODULES:
                found.append('from ' + str(node.module))
        elif isinstance(node, ast.Attribute):
            if node.attr in BLOCKED_ATTRIBUTES:
                found.append('attribute ' + node.attr)
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            for needle in NEEDLES:
                if needle in node.value:
                    found.append('literal host or url')
    return found


